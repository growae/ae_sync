import { writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import type { CompiledContract } from '../sync/types.js'

export function generateEnvDtsContent(
  contracts: Map<string, CompiledContract>,
): string {
  const eventNames: string[] = []

  for (const [contractName, contract] of contracts) {
    for (const event of contract.events) {
      eventNames.push(`'${contractName}:${event.name}'`)
    }
  }

  const eventNameType =
    eventNames.length > 0 ? eventNames.join(' | ') : 'string'

  return `// Auto-generated by @growae/aesync — do not edit

declare module 'aesync:registry' {
  interface AeSyncRegistry {
    fns: Array<{ name: string; fn: (...args: any[]) => Promise<void> }>
    _api_routes: Array<{ method: string; path: string; handler: (...args: any[]) => any }>
    _api_middleware: Array<(...args: any[]) => any>
    on(name: ${eventNameType}, fn: (...args: any[]) => Promise<void>): void
    get(path: string, handler: (...args: any[]) => any): void
    post(path: string, handler: (...args: any[]) => any): void
    use(handler: (...args: any[]) => any): void
  }
  export const aesync: AeSyncRegistry
}

declare module 'aesync:schema' {
  export * from './schema.js'
}

declare module 'aesync:api' {
  export let db: any
  export let client: any
  export function setDb(d: any): void
  export function setClient(c: any): void
}
`
}

export async function generateEnvDts(
  rootDir: string,
  contracts: Map<string, CompiledContract>,
): Promise<void> {
  const content = generateEnvDtsContent(contracts)
  await writeFile(resolve(rootDir, 'aesync-env.d.ts'), content)
}
